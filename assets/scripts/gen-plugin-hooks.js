#!/usr/bin/env node
/**
 * Writes js/plugins.generated.ts: one import per installed plugin that ships
 * LiveView hooks (plugins/<slug>/assets/js/index.ts exporting `hooks`), merged
 * into `PluginHooks`, which app.ts hands to the LiveSocket. BACON8.md §9.
 *
 * Runs before every JS build (npm pre-scripts). The output is gitignored, so a
 * private plugin cloned into plugins/ never ends up referenced in the public repo.
 */
const fs = require('fs');
const path = require('path');

const ASSETS = path.join(__dirname, '..');
const PLUGINS = path.join(ASSETS, '..', 'plugins');
const OUT = path.join(ASSETS, 'js', 'plugins.generated.ts');

const slugs = fs.existsSync(PLUGINS)
  ? fs.readdirSync(PLUGINS)
      .filter((name) => /^[a-z][a-z0-9_]*$/.test(name))
      .filter((name) => fs.existsSync(path.join(PLUGINS, name, 'assets', 'js', 'index.ts')))
      .sort()
  : [];

const camel = (slug) => slug.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

const lines = [
  '// GENERATED by assets/scripts/gen-plugin-hooks.js - do not edit, not committed.',
  '// Hooks from every installed plugin; inactive plugins\' pages never mount them.',
  ...slugs.map((slug) => `import { hooks as ${camel(slug)} } from "../../plugins/${slug}/assets/js/index";`),
  '',
  `export const PluginHooks: Record<string, object> = {${slugs.map((s) => ` ...${camel(s)}`).join(',')}${slugs.length ? ' ' : ''}};`,
  '',
];

const next = lines.join('\n');
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
if (prev !== next) fs.writeFileSync(OUT, next);
console.log(`plugin hooks: ${slugs.length ? slugs.join(', ') : '(none)'}`);
